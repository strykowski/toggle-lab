for (const [c, g] of Object.entries(G)) if (g.length !== 35) throw new Error(`font5x7: glyph "${c}" is ${g.length} cells`);

export const GLYPH_W = 5, GLYPH_H = 7;
export const isSupported = (c) => String(c).toUpperCase() in G;

// Text → { w, h, at(x, y) }, with 1 column of space between letters.
export function rasterize(text) {
  const chars = [...String(text).toUpperCase()].map((c) => G[c] ?? G[" "]);
  const w = Math.max(0, chars.length * (GLYPH_W + 1) - 1);
  return {
    w, h: GLYPH_H,
    at(x, y) {
      if (x < 0 || y < 0 || x >= w || y >= GLYPH_H) return false;
      const ci = Math.floor(x / (GLYPH_W + 1)), cx = x % (GLYPH_W + 1);
      return cx < GLYPH_W && chars[ci][y * GLYPH_W + cx] === "#";
    },
  };
}
